#!/usr/bin/env python3
# =============================================================================
# Pi-hole Suite REST API  (OPTIONAL COMPONENT)
# =============================================================================
# This is an *optional* companion API for the Pi-hole + Unbound setup.
# It is NOT required for the core DNS stack (Pi-hole + Unbound) to work.
#
# What it provides:
#   GET /health          - uptime / version
#   GET /version         - app version
#   GET /urls            - detected service URLs
#   GET /pihole          - Pi-hole version + FTL status
#   GET /unbound         - Unbound port + dig test
#   GET /dns?limit=N     - last N DNS log entries
#   GET /leases?limit=N  - DHCP leases
#   GET /stats           - summary stats
#
# Authentication: X-API-Key header  (SUITE_API_KEY env var required)
# Default port:   8090              (SUITE_PORT env var)
# Default bind:   127.0.0.1         (SUITE_HOST env var)
#
# Start:   python3 start_suite.py
# Deps:    pip install -r requirements.txt
# Docs:    GET /docs  (Swagger UI auto-generated by FastAPI)
# =============================================================================
import os
import json
import re
import subprocess
import time
from collections import deque
from typing import Any
from urllib.request import Request, urlopen

import uvicorn
from fastapi import Depends, FastAPI, Header, HTTPException
from fastapi.staticfiles import StaticFiles

from maintenance_web import MaintenanceSettings, configure_maintenance_security, create_maintenance_router

APP_VERSION = "1.0.0"
START_TIME = time.time()


def _env(name: str, default: str | None = None) -> str:
    value = os.getenv(name)
    if value is None or value == "":
        if default is None:
            raise RuntimeError(f"Missing required environment variable: {name}")
        return default
    return value


def require_api_key(x_api_key: str | None = Header(default=None, alias="X-API-Key")) -> None:
    expected = _env("SUITE_API_KEY", default="")
    if expected == "":
        raise HTTPException(status_code=500, detail="Server not configured: SUITE_API_KEY missing")
    if x_api_key != expected:
        raise HTTPException(status_code=401, detail="Unauthorized")


app = FastAPI(
    title="Pi-hole Suite API",
    version=APP_VERSION,
    docs_url=None,
    redoc_url=None,
    openapi_url=None,
)
maintenance_settings = MaintenanceSettings.from_environment()
configure_maintenance_security(app, maintenance_settings)
app.include_router(create_maintenance_router(maintenance_settings))

# Mount dashboard if it exists
if os.path.isdir(os.path.join(os.path.dirname(__file__), "dashboard")):
    app.mount("/dashboard", StaticFiles(directory=os.path.join(os.path.dirname(__file__), "dashboard"), html=True), name="dashboard")

def _read_lines(path: str, limit: int) -> list[str] | None:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return list(deque(f, maxlen=limit))
    except OSError:
        return None


def _run(cmd: list[str], timeout: float = 2.0) -> dict[str, Any]:
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False)
        return {
            "ok": True,
            "cmd": cmd,
            "returncode": p.returncode,
            "stdout": p.stdout.strip(),
            "stderr": p.stderr.strip(),
        }
    except (OSError, subprocess.TimeoutExpired) as e:
        return {"ok": False, "cmd": cmd, "error": str(e)}


def _guess_host_ip() -> str:
    # Best-effort: pick first host IP; used for URL display.
    # Never blocks for long.
    r = _run(["hostname", "-I"], timeout=1.0)
    if r.get("ok") and r.get("stdout"):
        first = r["stdout"].split()[0]
        if first:
            return first

    r = _run(["ip", "-4", "route", "get", "1.1.1.1"], timeout=1.0)
    if r.get("ok") and r.get("stdout"):
        m = re.search(r"src\s+(\d+\.\d+\.\d+\.\d+)", r["stdout"])
        if m:
            return m.group(1)

    return "127.0.0.1"


def _http_ok(url: str, timeout: float = 1.5) -> bool:
    try:
        req = Request(url, method="GET")
        with urlopen(req, timeout=timeout) as resp:
            return 200 <= resp.status < 500
    except Exception:
        return False


def _parse_pihole_log(limit: int) -> list[dict[str, Any]] | None:
    # Best-effort parser for classic Pi-hole log format.
    # If no candidate is present and readable, report unavailable.
    candidates = [
        "/var/log/pihole/pihole.log",
        "/var/log/pihole.log",
    ]
    lines: list[str] | None = None
    for p in candidates:
        lines = _read_lines(p, limit * 3)
        if lines is not None:
            break

    if lines is None:
        return None

    out: list[dict[str, Any]] = []
    for line in reversed(lines):
        # A syslog record is short. Ignore oversized/corrupt records before
        # parsing, and use bounded splitting instead of regex on log content.
        if len(line) > 8192:
            continue
        marker = " query["
        marker_at = line.find(marker)
        if marker_at < 0:
            continue
        prefix = line[:marker_at]
        daemon_at = prefix.find(" dnsmasq[")
        timestamp = " ".join((prefix[:daemon_at] if daemon_at >= 0 else prefix).split()[-3:])
        query_start = line.find("] ", marker_at)
        if query_start < 0:
            continue
        query_end = line.find(" from ", query_start + 2)
        if query_end < 0:
            continue
        query = line[query_start + 2:query_end]
        client_fields = line[query_end + 6:].split(None, 1)
        client = client_fields[0] if client_fields else ""
        if not timestamp or not query or not client:
            continue
        out.append(
            {
                "timestamp": timestamp,
                "client": client,
                "query": query,
                "action": "query",
            }
        )
        if len(out) >= limit:
            break

    return list(reversed(out))


def _parse_dhcp_leases(limit: int) -> list[dict[str, Any]] | None:
    # Pi-hole DHCP leases file: /etc/pihole/dhcp.leases
    # Format: <expiry_epoch> <mac> <ip> <hostname> <clientid>
    # We only have expiry; lease_start may be unknown.
    import datetime

    path = "/etc/pihole/dhcp.leases"
    lines = _read_lines(path, limit * 3)
    if lines is None:
        return None
    out: list[dict[str, Any]] = []

    def to_iso(epoch: str) -> str | None:
        try:
            ts = int(epoch)
        except ValueError:
            return None
        return datetime.datetime.fromtimestamp(ts, tz=datetime.timezone.utc).isoformat()

    for line in reversed(lines):
        parts = line.strip().split()
        if len(parts) < 4:
            continue
        expiry, mac, ip, hostname = parts[0:4]
        out.append(
            {
                "ip": ip,
                "mac": mac,
                "hostname": hostname,
                "lease_start": None,
                "lease_end": to_iso(expiry) or expiry,
            }
        )
        if len(out) >= limit:
            break

    return list(reversed(out))


def _read_pihole_v6_upstreams() -> list[str] | None:
    result = _run(["/usr/local/libexec/pihole-suite-upstreams"], timeout=2.0)
    if not result.get("ok") or result.get("returncode") != 0 or result.get("stderr"):
        return None
    try:
        upstreams = json.loads(result.get("stdout", ""))
    except (ValueError, TypeError):
        return None
    return upstreams if isinstance(upstreams, list) and all(isinstance(v, str) for v in upstreams) else None


@app.get("/health", dependencies=[Depends(require_api_key)])
def health() -> dict[str, Any]:
    return {
        "ok": True,
        "message": "Pi-hole Suite API is running",
        "version": APP_VERSION,
        "uptime_seconds": int(time.time() - START_TIME),
    }


@app.get("/version", dependencies=[Depends(require_api_key)])
def version() -> dict[str, Any]:
    return {
        "app": "pihole-suite",
        "version": APP_VERSION,
        "uptime_seconds": int(time.time() - START_TIME),
    }


@app.get("/urls", dependencies=[Depends(require_api_key)])
def urls() -> dict[str, Any]:
    host_ip = _guess_host_ip()
    suite_port = int(_env("SUITE_PORT", default="8090"))
    netalertx_port = int(_env("NETALERTX_PORT", default="20211"))

    return {
        "host_ip": host_ip,
        "pihole_admin": f"http://{host_ip}/admin",
        "netalertx": f"http://{host_ip}:{netalertx_port}",
        "suite_local": f"http://127.0.0.1:{suite_port}",
        "note": "Suite binds to 127.0.0.1 by default; access remotely via a reverse proxy if needed.",
    }


@app.get("/pihole", dependencies=[Depends(require_api_key)])
def pihole() -> dict[str, Any]:
    v = _run(["pihole", "-v"], timeout=2.0)
    ftl = _run(["systemctl", "is-active", "pihole-FTL"], timeout=2.0)
    upstreams = _read_pihole_v6_upstreams()

    return {
        "pihole_version": v.get("stdout", "") if v.get("ok") else "unknown",
        "ftl_active": (ftl.get("ok") and ftl.get("returncode") == 0),
        "upstreams": upstreams,
    }


@app.get("/unbound", dependencies=[Depends(require_api_key)])
def unbound() -> dict[str, Any]:
    unbound_port = int(_env("UNBOUND_PORT", default="5335"))
    svc = _run(["systemctl", "is-active", "unbound"], timeout=2.0)
    dig = _run(
        [
            "dig",
            "+short",
            "@127.0.0.1",
            "-p",
            str(unbound_port),
            "+time=1",
            "+tries=1",
            "cloudflare.com",
        ],
        timeout=2.0,
    )

    ok = bool(dig.get("ok") and dig.get("stdout"))

    return {
        "port": unbound_port,
        "service_active": (svc.get("ok") and svc.get("returncode") == 0),
        "dig_ok": ok,
        "dig_result": dig.get("stdout", ""),
    }


@app.get("/netalertx", dependencies=[Depends(require_api_key)])
def netalertx() -> dict[str, Any]:
    port = int(_env("NETALERTX_PORT", default="20211"))
    url = f"http://127.0.0.1:{port}/"
    reachable = _http_ok(url)

    return {
        "port": port,
        "url_local": url,
        "http_reachable": reachable,
    }


@app.get("/dns", dependencies=[Depends(require_api_key)])
def dns(limit: int = 50) -> list[dict[str, Any]]:
    limit = max(1, min(limit, 500))
    entries = _parse_pihole_log(limit)
    if entries is None:
        raise HTTPException(status_code=503, detail="DNS log unavailable")
    return entries


@app.get("/devices", dependencies=[Depends(require_api_key)])
def devices() -> list[dict[str, Any]]:
    # Placeholder: device discovery depends on NetAlertX (formerly Pi.Alert)
    # APIs and is environment-specific.
    raise HTTPException(status_code=503, detail="Device discovery is not configured")


@app.get("/leases", dependencies=[Depends(require_api_key)])
def leases(limit: int = 200) -> list[dict[str, Any]]:
    limit = max(1, min(limit, 2000))
    entries = _parse_dhcp_leases(limit)
    if entries is None:
        raise HTTPException(status_code=503, detail="DHCP leases unavailable")
    return entries


@app.get("/stats", dependencies=[Depends(require_api_key)])
def stats() -> dict[str, Any]:
    recent = _parse_pihole_log(100)
    return {
        "total_dns_logs": len(recent) if recent is not None else None,
        "total_devices": None,
        "recent_queries": len(recent) if recent is not None else None,
        "note": "DNS stats are derived from best-effort log parsing; may be empty depending on Pi-hole logging/permissions.",
    }


def main() -> None:
    port = int(_env("SUITE_PORT", default="8090"))
    host = _env("SUITE_HOST", default="127.0.0.1")
    if host != "127.0.0.1":
        raise RuntimeError("SUITE_HOST must be 127.0.0.1 for the maintenance web service")
    uvicorn.run(app, host=host, port=port, log_level=os.getenv("SUITE_LOG_LEVEL", "info").lower())


if __name__ == "__main__":
    main()
